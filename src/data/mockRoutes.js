function haversineDistance(path) {
  let meters = 0;

  for (let index = 1; index < path.length; index += 1) {
    const [lat1, lng1] = path[index - 1];
    const [lat2, lng2] = path[index];
    const toRad = Math.PI / 180;
    const deltaLat = (lat2 - lat1) * toRad;
    const deltaLng = (lng2 - lng1) * toRad;
    const a =
      Math.sin(deltaLat / 2) ** 2 +
      Math.cos(lat1 * toRad) *
        Math.cos(lat2 * toRad) *
        Math.sin(deltaLng / 2) ** 2;

    meters += 6371000 * 2 * Math.asin(Math.sqrt(a));
  }

  return meters / 1000;
}

